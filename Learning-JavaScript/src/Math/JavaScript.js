//Math.round() làm tròn đến số nguyên gần nhất.
console.log(Math.round(4.7)); // 5
console.log(Math.round(4.4)); // 4

//Math.floor() làm tròn xuống.
console.log(Math.floor(4.7)); // 4
console.log(Math.floor(4.4)); // 4

//Math.ceil() làm tròn lên.
console.log(Math.ceil(4.1)); // 5

//Math.trunc() loại bỏ phần thập phân.
console.log(Math.trunc(4.9)); // 4
console.log(Math.trunc(-4.9)); // -4

//Math.abs() lấy giá trị tuyệt đối.
console.log(Math.abs(-10)); // 10

//Math.max() trả về số lớn nhất trong danh sách các đối số.
console.log(Math.max(1, 2, 3, 4, 5)); // 5

//Math.min() trả về số nhỏ nhất trong danh sách các đối số.
console.log(Math.min(1, 2, 3, 4, 5)); // 1

//Math.random() trả về một số ngẫu nhiên.
console.log(Math.random()); // 0.123456789 (ví dụ)

console.log(Math.floor(Math.random() * 10) + 1);
